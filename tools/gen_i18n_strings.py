#!/usr/bin/env python3
"""Generates src/i18n_strings.c from assets/translations.csv.

assets/translations.csv holds the touchscreen texts: one row per text, the
English column is the key passed to tr(). The image installs it as the
default translation file, and this table built into the program is the
fallback when a translation file is missing or a text in it is rejected.

Edit the CSV, then run from the repository root:
    python3 tools/gen_i18n_strings.py
    python3 tools/check_i18n.py
"""
import csv
import re

CSV_FILE = "assets/translations.csv"
C_FILE = "src/i18n_strings.c"
# Columns of i18n_entry_t, in order.
CODES = ("en", "es", "de", "zh-hans", "ar")
HEADER_CODE = re.compile(r"\(([a-z]{2,3}(?:-[a-z0-9]{2,8})?)\)\s*$")

PREAMBLE = """\
/* Touchscreen translations built into the program: one entry per text shown
 * by the app. GENERATED by tools/gen_i18n_strings.py from
 * assets/translations.csv: edit the CSV, not this file.
 *
 * The English text is the key passed to tr(). Translations must keep every
 * printf conversion (%s, %d...) in the same order and every "#RRGGBB text#"
 * color command balanced; tools/check_i18n.py checks both, and that every
 * tr() key is listed.
 * Columns: English, Spanish, German, Chinese (Simplified), Arabic. */

#include <stddef.h>

#include "i18n.h"

const i18n_entry_t I18N_STRINGS[] = {
"""


def read_rows(path=CSV_FILE):
    """Returns the CSV rows as lists ordered like CODES ("" = untranslated)."""
    with open(path, encoding="utf-8-sig", newline="") as f:
        reader = csv.reader(f)
        header = next(reader)
        columns = {}
        for index, title in enumerate(header):
            m = HEADER_CODE.search(title)
            if m:
                columns[m.group(1)] = index
        missing = [c for c in CODES if c not in columns]
        if missing:
            raise SystemExit(f"{path}: no column for {missing}")
        rows = []
        for record in reader:
            if not any(record):
                continue
            record += [""] * (len(header) - len(record))
            rows.append([record[columns[c]].replace("\r\n", "\n") for c in CODES])
    return rows


def c_literal(text):
    out = text.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n")
    return '"' + out + '"'


def render(rows):
    """The C source of the table."""
    lines = [PREAMBLE]
    for row in rows:
        lines.append("\t{\n")
        for text in row:
            lines.append("\t\t" + (c_literal(text) if text else "NULL") + ",\n")
        lines.append("\t},\n")
    lines.append("};\n\nconst unsigned I18N_STRING_COUNT =\n\t\tsizeof(I18N_STRINGS) / sizeof(I18N_STRINGS[0]);\n")
    return "".join(lines)


def main():
    rows = read_rows()
    if any(not row[0] for row in rows):
        raise SystemExit(f"{CSV_FILE}: a row has no English text")
    with open(C_FILE, "w", encoding="utf-8") as f:
        f.write(render(rows))
    print(f"{C_FILE}: {len(rows)} entries")


if __name__ == "__main__":
    main()
