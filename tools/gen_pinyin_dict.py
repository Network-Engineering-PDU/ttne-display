#!/usr/bin/env python3
"""Generates src/pinyin_dict.c: the Pinyin dictionary of the Chinese
touchscreen keyboard (LVGL lv_ime_pinyin).

The characters are the 3755 common Simplified Chinese characters (GB 2312
level 1). Each syllable lists its characters most frequent first, so the
usual one is the first candidate.

Needs pypinyin (readings) and jieba (character frequencies), both MIT:
    pip3 install pypinyin jieba
    python3 tools/gen_pinyin_dict.py
"""
import collections
import os

import jieba
from pypinyin import Style, pinyin

C_FILE = "src/pinyin_dict.c"


def common_characters():
    chars = []
    for high in range(0xB0, 0xD8):
        for low in range(0xA1, 0xFF):
            try:
                chars.append(bytes([high, low]).decode("gb2312"))
            except UnicodeDecodeError:
                pass
    return chars


def frequencies():
    freq = {}
    path = os.path.join(os.path.dirname(jieba.__file__), "dict.txt")
    with open(path, encoding="utf-8") as f:
        for line in f:
            word, count = line.split()[:2]
            if len(word) == 1:
                freq[word] = int(count)
    return freq


def main():
    chars = common_characters()
    order = {c: i for i, c in enumerate(chars)}
    freq = frequencies()
    # syllable -> {char: rank}: a character's main reading ranks it by its
    # frequency; its other readings (的 di, 行 hang) put it after the others
    syllables = collections.defaultdict(dict)
    for char in chars:
        readings = pinyin(char, style=Style.NORMAL, heteronym=True)[0]
        for n, reading in enumerate(readings):
            reading = reading.replace("ü", "v")     # typed as v: lv, nv
            if reading.isascii() and reading.isalpha() and char not in syllables[reading]:
                main = n == 0
                syllables[reading][char] = (0 if main else 1, -freq.get(char, 0), order[char])
    # LVGL indexes the dictionary by first letter and needs every letter
    # from a to z; no syllable starts with i, u or v.
    for letter in "iuv":
        syllables.setdefault(letter, {})

    lines = [
        "/* Pinyin dictionary of the Chinese keyboard: syllable -> characters,\n",
        " * most frequent first. GENERATED by tools/gen_pinyin_dict.py. */\n\n",
        '#include "pinyin_dict.h"\n\n',
        "lv_pinyin_dict_t pinyin_dict[] = {\n",
    ]
    for reading in sorted(syllables):
        ranked = sorted(syllables[reading], key=syllables[reading].get)
        lines.append(f'\t{{ "{reading}", "{"".join(ranked)}" }},\n')
    lines.append("\t{ NULL, NULL },\n};\n")
    with open(C_FILE, "w", encoding="utf-8") as f:
        f.write("".join(lines))
    print(f"{C_FILE}: {len(syllables)} syllables, {len(chars)} characters")


if __name__ == "__main__":
    main()
